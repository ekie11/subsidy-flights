def city(code: str) -> str:
    code = (code or "").upper()
    return AIRPORTS.get(code, (code, "", False))[0]


def label(code: str) -> str:
    """«Хабаровск (KHV)» — для выпадающих списков."""
    code = (code or "").upper()
    if code not in AIRPORTS:
        return code
    return f"{AIRPORTS[code][0]} ({code})"


def is_dfo(code: str) -> bool:
    return AIRPORTS.get((code or "").upper(), ("", "", False))[2]


def as_json_dict() -> dict[str, dict]:
    return {
        code: {"city": c, "airport": a, "dfo": d}
        for code, (c, a, d) in AIRPORTS.items()
    }


